import { expect, it } from 'vitest';
import { stockDays } from '../../src/services/inventory';
import { priceAtThirtyDays, pendingMilestone, nextVietnamMidnight } from '../../src/domain/inventory';
import { initialSalePrice } from '../../src/domain/purchases';
import { validateBracket, confirmedConditions } from '../../src/services/reference-data/local';
import { crc16Ccitt, createVietQr } from '../../src/lib/payment/vietqr';
import { salesSubtotal, calculateSalesPromotion } from '../../src/domain/sales';

// Original cases/assertions moved verbatim; no database or account setup.
const bracketInput = { productType: '?o', brand: 'Nh?n th?', condition: '2', min: '50000', max: '150000' };

it.each([
  ['2026-11-01', '2026-11-10T16:59:59Z', 9], ['2026-11-01', '2026-11-10T17:00:00Z', 10],
  ['2024-02-28', '2024-03-01T00:00:00+07:00', 2], ['2026-12-31', '2027-01-01T00:00:00+07:00', 1],
])('computes calendar stock days %s at %s without device timezone dependence', (date, at, expected) => {
  expect(stockDays(date, new Date(at))).toBe(expected);
});

it.each([[1, 1], [5, 4], [10, 7], [104007, 72805]])('rounds original cycle price %s to final 70%% price %s half-up', (original, expected) => {
  expect(priceAtThirtyDays(original)).toBe(expected);
});

it('prioritizes 45 over missed 30, never applies a milestone twice, and schedules the next Vietnam midnight', () => {
  expect(pendingMilestone('2026-01-01', '2026-01-30', [])).toBeUndefined();
  expect(pendingMilestone('2026-01-01', '2026-01-31', [])).toBe(30);
  expect(pendingMilestone('2026-01-01', '2026-02-14', [30])).toBeUndefined();
  expect(pendingMilestone('2026-01-01', '2026-02-15', [])).toBe(45);
  expect(pendingMilestone('2026-01-01', '2026-02-15', [30])).toBe(45);
  expect(pendingMilestone('2026-01-01', '2026-03-01', [45])).toBeUndefined();
  expect(nextVietnamMidnight(new Date('2026-11-12T16:59:59Z')).toISOString()).toBe('2026-11-12T17:00:00.000Z');
});

it.each([[1, 1], [5, 7], [15, 20], [80001, 104001], [120000, 156000], [6928614811339224, 9007199254740991]])('uses approved integer half-up markup %s -> %s', (cost, expected) => {
  expect(initialSalePrice(cost)).toBe(expected);
});

it('rejects fractional/zero/unsafe costs and sale price overflow', () => {
  for (const cost of [0, -1, 0.5, NaN, Infinity, Number.MAX_SAFE_INTEGER]) expect(() => initialSalePrice(cost)).toThrow();
});

it('checks every required bracket field and integer Min/Max boundaries', () => {
  for (const key of Object.keys(bracketInput)) expect(() => validateBracket({ ...bracketInput, [key]: '' }, confirmedConditions)).toThrow();
  for (const data of [{ min: '0' },{ max: '-1' },{ min: '1.2' },{ min: '150001' },{ max: '9007199254740992' }]) expect(() => validateBracket({ ...bracketInput, ...data }, confirmedConditions)).toThrow();
  expect(validateBracket({ ...bracketInput, min: '150000' }, confirmedConditions).min).toBe(150000);
});

it('matches independent CRC vectors and rejects invalid QR inputs', () => {
  expect(crc16Ccitt('123456789')).toBe('29B1');
  // Published NAPAS v1.0 example, not generated by this implementation.
  expect(crc16Ccitt('00020101021138570010A00000072701270006970403011200110123456780208QRIBFTTA53037045802VN6304')).toBe('F4E5');
  for (const amount of [0, -1, 1.5, Number.MAX_SAFE_INTEGER, NaN, Infinity]) expect(() => createVietQr(amount, 'BH00000001')).toThrow();
  expect(() => createVietQr(100, 'BH<script>')).toThrow();
});

it('rejects safe-integer subtotal overflow', () => {
  const selectedAt = '2026-11-13T00:00:00.000Z';
  const line = (productId: string, amount: number) => ({
    productId, sourcePurchaseId: 'TM00000001', name: 'Áo', quantity: 1 as const,
    unitPrice: amount, lineTotal: amount, productVersion: 1, selectedAt,
  });
  expect(salesSubtotal([line('SP00000001', Number.MAX_SAFE_INTEGER)])).toBe(Number.MAX_SAFE_INTEGER);
  expect(() => salesSubtotal([line('SP00000001', Number.MAX_SAFE_INTEGER), line('SP00000002', 1)])).toThrow('vượt quá giới hạn');
});

it('rounds member discount on subtotal and awards points only on the amount actually paid', () => {
  expect(calculateSalesPromotion({
    subtotal: 100_003, isMember: true, pointsBalance: 51, useMembershipDiscount: true,
  })).toEqual({
    subtotal: 100_003, discount: 20_001, total: 80_002, isMember: true,
    pointsBefore: 51, pointsUsed: 50, pointsEarned: 8, pointsAfter: 9,
  });
  expect(calculateSalesPromotion({
    subtotal: 100_002, isMember: true, pointsBalance: 50, useMembershipDiscount: true,
  }).discount).toBe(20_000);
});

it('requires 50 member points for the discount and allows members not to use it', () => {
  expect(() => calculateSalesPromotion({
    subtotal: 50_000, isMember: true, pointsBalance: 49, useMembershipDiscount: true,
  })).toThrow('tối thiểu 50 điểm');
  expect(calculateSalesPromotion({
    subtotal: 50_000, isMember: true, pointsBalance: 49, useMembershipDiscount: false,
  })).toMatchObject({ discount: 0, total: 50_000, pointsUsed: 0, pointsEarned: 5, pointsAfter: 54 });
});

it('does not grant member benefits to nonmembers or change their point balance', () => {
  expect(calculateSalesPromotion({
    subtotal: 50_000, isMember: false, pointsBalance: 0, useMembershipDiscount: false,
  })).toMatchObject({ discount: 0, total: 50_000, pointsUsed: 0, pointsEarned: 0, pointsAfter: 0 });
  expect(() => calculateSalesPromotion({
    subtotal: 50_000, isMember: false, pointsBalance: 0, useMembershipDiscount: true,
  })).toThrow('Chỉ thành viên');
});

it('rejects applying member points to an empty cart and point balance overflow', () => {
  expect(() => calculateSalesPromotion({
    subtotal: 0, isMember: true, pointsBalance: 50, useMembershipDiscount: true,
  })).toThrow('giỏ hàng trống');
  expect(() => calculateSalesPromotion({
    subtotal: Number.MAX_SAFE_INTEGER, isMember: true, pointsBalance: 0, useMembershipDiscount: false,
  })).toThrow('vượt quá giới hạn');
});
